  async findAll(searchQuery?: string): Promise<Person[]> {
    if (!searchQuery) return this.members;
    const query = searchQuery.toLowerCase();
    return this.members.filter(m => 
      m.firstName.toLowerCase().includes(query) || 
      m.lastName.toLowerCase().includes(query) || 
      m.phone.toLowerCase().includes(query)
    );
  }

  async findById(id: string): Promise<Person | null> {
    return this.members.find(m => m.id === id) || null;
  }

  async create(data: Prisma.PersonCreateInput): Promise<Person> {
    const newMember: Person = {
      id: Math.random().toString(36).substring(7),
      userId: data.user?.connect?.id ?? null,
      firstName: data.firstName,
      lastName: data.lastName,
      phone: data.phone,
      role: (data.role as Role) || Role.MEMBER,
      gender: data.gender ?? true,
      hasBaptized: data.hasBaptized || false,
      bod: data.bod ? new Date(data.bod as string) : null,
      assignedAt: new Date(),
      createdAt: new Date(),
      deletedAt: null,
      profileImgUrl: (data.profileImgUrl as string) || null,
      kakaoAccount: (data.kakaoAccount as string) || null,
      occupation: (data.occupation as string) || null,
      visaType: (data.visaType as VisaType) || null,
      address: (data.address as string) || null,
      note: (data.note as string) || null,
      groupId: data.group?.connect?.id ?? "mock-group-id",
    };
    this.members.push(newMember);
    return newMember;
  }

  async update(id: string, data: Prisma.PersonUpdateInput): Promise<Person> {
    const index = this.members.findIndex(m => m.id === id);
    if (index === -1) throw new Error("Member not found");
    
    const updated = {
      ...this.members[index],
      ...(typeof data.firstName === 'string' && { firstName: data.firstName }),
      ...(typeof data.lastName === 'string' && { lastName: data.lastName }),
      ...(typeof data.phone === 'string' && { phone: data.phone }),
      ...(data.role && { role: data.role as Role }),
      ...(data.gender !== undefined && { gender: data.gender as boolean }),
    };
    this.members[index] = updated as Person;
    return this.members[index];
  }

  async delete(id: string): Promise<void> {
    this.members = this.members.filter(m => m.id !== id);
  }
